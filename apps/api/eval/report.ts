/**
 * Turns a compiler eval run (scripts/eval-compiler.ts) into compiler-results.md.
 * Pure: takes the raw run, returns Markdown.
 */
import type { TokenUsage } from "../src/llm/provider.js";
import type { CaseScore } from "./score.js";

export interface EvalConfig {
  name: string;
  description: string;
  tier?: "fast" | "balanced" | "deep";
  model?: string;
  maxAttempts?: number;
}

export interface EvalRecord extends CaseScore {
  config: string;
  repeat: number;
  model: string | null;
  tier: string | null;
  routingReasons: string[];
  /** null when the model has no entry in the price table. */
  costUsd: number | null;
}

export interface EvalRun {
  startedAt: string;
  finishedAt: string;
  compilerMode: string;
  casesStatus: string;
  caseCount: number;
  repeats: number;
  tierModels: Record<string, string>;
  /** USD per million tokens. */
  prices: Record<string, { input: number; output: number; cacheRead: number; cacheWrite: number }>;
  pricesAsOf: string;
  configs: EvalConfig[];
  records: EvalRecord[];
  totalCostUsd: number;
  stoppedEarly?: string;
}

export function costOf(usage: TokenUsage, price: EvalRun["prices"][string] | undefined): number | null {
  if (!price) return null;
  return (
    (usage.inputTokens * price.input +
      usage.outputTokens * price.output +
      usage.cacheReadTokens * price.cacheRead +
      usage.cacheWriteTokens * price.cacheWrite) /
    1_000_000
  );
}

export function percentile(values: number[], p: number): number {
  if (values.length === 0) return 0;
  const sorted = [...values].sort((a, b) => a - b);
  const idx = Math.min(sorted.length - 1, Math.ceil((p / 100) * sorted.length) - 1);
  return sorted[Math.max(0, idx)]!;
}

const pct = (n: number, d: number) => (d === 0 ? "-" : `${((100 * n) / d).toFixed(1)}%`);
const mean = (xs: number[]) => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : 0);
const usd = (n: number) => `$${n.toFixed(n < 0.01 ? 5 : 4)}`;

export interface ConfigSummary {
  config: string;
  compiles: number;
  validPct: string;
  matchPct: string;
  avgAttempts: string;
  p50Ms: number;
  p95Ms: number;
  avgCost: string;
  totalCost: number;
}

export function summarize(config: string, records: EvalRecord[]): ConfigSummary {
  const rs = records.filter((r) => r.config === config);
  const latencies = rs.map((r) => r.latencyMs);
  const costs = rs.map((r) => r.costUsd).filter((c): c is number => c !== null);
  const total = costs.reduce((a, b) => a + b, 0);
  return {
    config,
    compiles: rs.length,
    validPct: pct(rs.filter((r) => r.valid).length, rs.length),
    matchPct: pct(rs.filter((r) => r.structuralMatch).length, rs.length),
    avgAttempts: mean(rs.map((r) => r.attempts)).toFixed(2),
    p50Ms: Math.round(percentile(latencies, 50)),
    p95Ms: Math.round(percentile(latencies, 95)),
    avgCost: costs.length < rs.length ? "n/a" : usd(mean(costs)),
    totalCost: total,
  };
}

function table(header: string[], rows: (string | number)[][]): string {
  return [
    `| ${header.join(" | ")} |`,
    `|${header.map(() => "---").join("|")}|`,
    ...rows.map((r) => `| ${r.join(" | ")} |`),
  ].join("\n");
}

export function renderReport(run: EvalRun): string {
  const out: string[] = [];
  out.push("# Compiler evaluation", "");
  out.push(
    `Generated by \`npm run eval:compiler -w apps/api\` on ${run.finishedAt.slice(0, 10)}.`,
    "",
    `- Cases: ${run.caseCount} (\`eval/compiler-cases.json\`, status: ${run.casesStatus})`,
    `- Repeats per case: ${run.repeats}`,
    `- Compiler mode: ${run.compilerMode}`,
    `- Tier models: ${Object.entries(run.tierModels).map(([t, m]) => `${t} = \`${m}\``).join(", ")}`,
    `- Total eval cost: ${usd(run.totalCostUsd)} (prices as of ${run.pricesAsOf})`,
  );
  if (run.compilerMode !== "claude") {
    out.push("", "> **Stub compiler run.** These numbers measure the offline keyword stub, not Claude.");
  }
  if (run.stoppedEarly) out.push("", `> **Stopped early:** ${run.stoppedEarly}`);

  out.push("", "## Headline", "");
  out.push(
    table(
      ["Config", "Compiles", "Valid", "Structural match", "Avg attempts", "p50 latency", "p95 latency", "Avg cost / compile"],
      run.configs.map((c) => {
        const s = summarize(c.name, run.records);
        return [`**${c.name}**: ${c.description}`, s.compiles, s.validPct, s.matchPct, s.avgAttempts, `${s.p50Ms} ms`, `${s.p95Ms} ms`, s.avgCost];
      }),
    ),
  );
  const flaky = flakyCases(run.records);
  if (run.repeats > 1) {
    const total = new Set(run.records.map((r) => `${r.config}|${r.caseId}`)).size;
    out.push(
      "",
      `Consistency across repeats: ${flaky.length} of ${total} case/config pairs gave mixed results (some repeats matched, some didn't)${flaky.length ? `: ${flaky.map((f) => `${f.caseId} (${f.config}, ${f.matched}/${f.runs})`).join(", ")}` : ""}.`,
    );
  }

  out.push("", ...byBucket(run), "", ...repairImpact(run), "", ...routingImpact(run), "", ...failureList(run));
  return out.join("\n") + "\n";
}

const hasConfig = (run: EvalRun, name: string) => run.records.some((r) => r.config === name);
const notRun = (names: string[]) =>
  `_Not in this run: needs the ${names.map((n) => `\`${n}\``).join(" and ")} config${names.length > 1 ? "s" : ""} (run with no config flags)._`;

/** Case/config pairs where some repeats matched and some didn't. */
export function flakyCases(records: EvalRecord[]) {
  const groups = new Map<string, EvalRecord[]>();
  for (const r of records) {
    const key = `${r.config}|${r.caseId}`;
    groups.set(key, [...(groups.get(key) ?? []), r]);
  }
  return [...groups.values()]
    .map((rs) => ({
      config: rs[0]!.config,
      caseId: rs[0]!.caseId,
      runs: rs.length,
      matched: rs.filter((r) => r.structuralMatch).length,
    }))
    .filter((g) => g.matched > 0 && g.matched < g.runs);
}

/** Section 2: match % per bucket, for the routed config (or the only config run). */
function byBucket(run: EvalRun): string[] {
  const config = hasConfig(run, "routed") ? "routed" : run.configs[0]?.name;
  const rs = run.records.filter((r) => r.config === config);
  const buckets = [...new Set(rs.map((r) => r.bucket))];
  const rows = buckets
    .map((b) => {
      const inBucket = rs.filter((r) => r.bucket === b);
      const matched = inBucket.filter((r) => r.structuralMatch).length;
      return { b, cases: new Set(inBucket.map((r) => r.caseId)).size, matched, total: inBucket.length };
    })
    .sort((x, y) => x.matched / x.total - y.matched / y.total);
  return [
    "## By bucket",
    "",
    `Config: \`${config}\`. Weakest bucket first.`,
    "",
    table(
      ["Bucket", "Cases", "Compiles", "Structural match"],
      rows.map((r) => [r.b, r.cases, r.total, pct(r.matched, r.total)]),
    ),
  ];
}

/** Section 3: routed with vs. without the validation-feedback repair retry. */
function repairImpact(run: EvalRun): string[] {
  const head = ["## Repair impact", ""];
  if (!hasConfig(run, "routed") || !hasConfig(run, "routed-no-repair")) {
    return [...head, notRun(["routed", "routed-no-repair"])];
  }
  const withRepair = summarize("routed", run.records);
  const without = summarize("routed-no-repair", run.records);
  const routed = run.records.filter((r) => r.config === "routed");
  const saved = routed.filter((r) => r.attempts === 2 && r.valid).length;
  const savedAndMatched = routed.filter((r) => r.attempts === 2 && r.structuralMatch).length;
  return [
    ...head,
    table(
      ["", "Valid", "Structural match", "Avg attempts", "Avg cost / compile"],
      [
        ["Without repair (1 attempt)", without.validPct, without.matchPct, without.avgAttempts, without.avgCost],
        ["With repair (up to 2 attempts)", withRepair.validPct, withRepair.matchPct, withRepair.avgAttempts, withRepair.avgCost],
      ],
    ),
    "",
    `In the routed config, the repair retry turned ${saved} of ${routed.length} compiles from invalid into valid graphs, and ${savedAndMatched} of those also matched every expectation. (The two configs are separate runs, so their match rates also differ by run-to-run noise.)`,
  ];
}

/** Section 4: routed vs. always-balanced, accuracy and cost, plus where the router sent each prompt. */
function routingImpact(run: EvalRun): string[] {
  const head = ["## Routing impact", ""];
  if (!hasConfig(run, "routed") || !hasConfig(run, "balanced")) {
    return [...head, notRun(["routed", "balanced"])];
  }
  const routed = summarize("routed", run.records);
  const balanced = summarize("balanced", run.records);
  const lines = [
    ...head,
    table(
      ["", "Structural match", "Avg cost / compile", "Total cost", "p50 latency"],
      [
        ["Routed", routed.matchPct, routed.avgCost, usd(routed.totalCost), `${routed.p50Ms} ms`],
        ["Always balanced", balanced.matchPct, balanced.avgCost, usd(balanced.totalCost), `${balanced.p50Ms} ms`],
      ],
    ),
  ];
  if (balanced.totalCost > 0) {
    const delta = (100 * (routed.totalCost - balanced.totalCost)) / balanced.totalCost;
    lines.push("", `Routing ${delta <= 0 ? "cut" : "raised"} cost by ${Math.abs(delta).toFixed(1)}% vs. always using the balanced tier.`);
  }

  // Where the router sent prompts, and how each tier did on them (routed config only).
  const rs = run.records.filter((r) => r.config === "routed");
  const tiers = ["fast", "balanced", "deep"].filter((t) => rs.some((r) => r.tier === t));
  lines.push(
    "",
    "Router decisions (routed config):",
    "",
    table(
      ["Tier", "Model", "Cases", "Structural match", "Buckets"],
      tiers.map((t) => {
        const inTier = rs.filter((r) => r.tier === t);
        const buckets = [...new Set(inTier.map((r) => r.bucket))].join(", ");
        return [t, `\`${run.tierModels[t] ?? "?"}\``, new Set(inTier.map((r) => r.caseId)).size, pct(inTier.filter((r) => r.structuralMatch).length, inTier.length), buckets];
      }),
    ),
  );

  // Cases the router sent to the fast tier that fast got wrong but balanced got right: likely mis-routes.
  const matchRate = (config: string, caseId: string) => {
    const xs = run.records.filter((r) => r.config === config && r.caseId === caseId);
    return xs.length ? xs.filter((r) => r.structuralMatch).length / xs.length : 0;
  };
  const misRouted = [...new Set(rs.filter((r) => r.tier === "fast").map((r) => r.caseId))].filter(
    (id) => matchRate("routed", id) < matchRate("balanced", id),
  );
  if (misRouted.length) {
    lines.push("", `Likely under-routed (sent to fast, and balanced did better): ${misRouted.join(", ")}.`);
  }
  return lines;
}

/** Section 5: every case that failed in any config, with each distinct reason. */
function failureList(run: EvalRun): string[] {
  const failed = run.records.filter((r) => !r.structuralMatch);
  const head = ["## Failures", ""];
  if (failed.length === 0) return [...head, "None: every compile matched its expectations."];

  const groups = new Map<string, EvalRecord[]>();
  for (const r of failed) {
    const key = `${r.caseId}|${r.config}`;
    groups.set(key, [...(groups.get(key) ?? []), r]);
  }
  const runsOf = (caseId: string, config: string) =>
    run.records.filter((r) => r.caseId === caseId && r.config === config).length;
  const caseOrder = [...new Set(run.records.map((r) => r.caseId))];
  const configOrder = run.configs.map((c) => c.name);
  const rows = [...groups.values()]
    .sort((a, b) => caseOrder.indexOf(a[0]!.caseId) - caseOrder.indexOf(b[0]!.caseId) || configOrder.indexOf(a[0]!.config) - configOrder.indexOf(b[0]!.config))
    .map((rs) => {
      const { caseId, bucket, config } = rs[0]!;
      const reasons = [...new Set(rs.flatMap((r) => r.failures))].map((f) => f.replace(/\|/g, "\\|"));
      return [caseId, bucket, config, `${rs.length}/${runsOf(caseId, config)}`, reasons.join("; ")];
    });
  return [...head, table(["Case", "Bucket", "Config", "Failed", "Reasons"], rows)];
}
